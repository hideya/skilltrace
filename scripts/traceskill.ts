async function main() {
  let [command, ...args] = process.argv.slice(2)
  if (command !== 'mcp') warnIfDevWrapperStale()

  if (command === 'start') {
    await start(args)
  } else if (command === 'end' || command === 'stop') {
    await end(args)
  } else if (command === 'status') {
    await status(args)
  } else if (command === 'serve') {
    runServe()
  } else if (command === 'daemon') {
    await daemon(args)
  } else if (command === 'mcp') {
    runScript('scripts/skilltrace-mcp.ts')
  } else {
    usage(command ? `Unknown command: ${command}` : 'Missing command')
  }
}

function warnIfDevWrapperStale() {
  if (!DEV_MODE) return

  let warnings = devWrapperWarnings()
  for (let warning of warnings) {
    console.warn(`Warning: ${warning}`)
  }
  if (warnings.length > 0) {
    console.warn('Run `pnpm skilltrace:install` from the SkillTrace checkout.')
  }
}

function devWrapperWarnings() {
  let binDir = path.join(os.homedir(), '.skilltrace/bin')
  let warnings: string[] = []

  for (let name of ['skilltrace-dev', 'traceskill-dev']) {
    let filePath = path.join(binDir, name)
    if (!fs.existsSync(filePath)) {
      warnings.push(`${name} is missing from ${binDir}.`)
      continue
    }

    let content = fs.readFileSync(filePath, 'utf8')
    if (!isCurrentDevWrapper(content)) {
      warnings.push(`${name} looks stale.`)
    }
  }

  return warnings
}

function isCurrentDevWrapper(content: string) {
  return (
    content.includes('# Generated by SkillTrace.') &&
    content.includes('SKILLTRACE_TARGET_ROOT="$(pwd -P') &&
    content.includes(PROJECT_ROOT) &&
    content.includes('scripts/traceskill.ts')
  )
}

async function start(args: string[]) {
  let options = parseArgs(args)
  let targetRoot = path.resolve(options.target || defaultTargetRoot())
  let server = options.server || process.env.SKILLTRACE_SERVER || DEFAULT_SERVER
  let probe = passiveProbeSupport()
  let sharedProbe = sharedProbeStatus(server)
  let traceMode = traceModeForStart(options)
  let shouldInjectInstructions = traceMode !== 'passive_only'
  let instructionSurfaces = detectInstructionSurfaces(targetRoot)
  let instructionProfile = selectInstructionProfile(
    options.instructionProfile,
    instructionSurfaces,
  )
  assertTraceTarget(targetRoot, instructionProfile.selected, instructionSurfaces)
  let instrumentation = withPassiveProbeWarning(
    assessInstrumentation(
      targetRoot,
      shouldInjectInstructions,
      instructionProfile.selected,
    ),
    probe,
  )
  let active = await getJson(server, '/api/sessions/status')
  if (active.session) {
    printActiveSessionRefusal(server, active.session)
    process.exit(1)
  }

  let useSharedProbe = sharedProbe.available
  if (probe.supported && probe.platform === 'darwin' && !useSharedProbe) primeSudo()
  cleanupTargetInjection(targetRoot)
  let gitSnapshot = captureGitSnapshot(targetRoot)

  let result = await postJson(server, '/api/sessions/start', {
    target_root: targetRoot,
    instrumentation,
    note: options.note,
    trace_mode: traceMode,
    git_snapshot: gitSnapshot,
    instruction_surfaces: instructionSurfaces,
    instruction_profile: instructionProfile,
  })
  printInstrumentationWarning(instrumentation, shouldInjectInstructions)
  let injection = shouldInjectInstructions
    ? injectInstructions(targetRoot, result.session.run_id, {
      traceMode,
      instructionProfile: instructionProfile.selected,
    })
    : null
  if (injection) {
    printInjectionResult('Instruction injection', injection)
    await postSessionEvent(server, result.session.run_id, 'instruction_injection_started', {
      ...injection,
      target_root: targetRoot,
    })
  }
  if (sharedProbe.requested && !sharedProbe.available) {
    printSharedProbeFallbackWarning(sharedProbe)
    await postSessionEvent(server, result.session.run_id, 'trace_probe_shared_unavailable', {
      reason: sharedProbe.reason,
      target_root: targetRoot,
    })
  }
  let worker: ProbeWorker | null = null
  let workerFailure: string | undefined
  let canStartRunProbe = !useSharedProbe && probe.supported && !sharedProbe.blocksRunProbe
  if (canStartRunProbe) {
    let candidate = startProbeWorker({
      runId: result.session.run_id,
      targetRoot,
      server,
      debug: options.debugProbe,
    })
    if (await waitForProbeStartup(candidate.pid)) {
      worker = candidate
    } else {
      workerFailure = `probe worker exited during startup; check ${candidate.logPath}`
    }
  }

  if (useSharedProbe && sharedProbe.state?.shared_probe_pid) {
    await postJson(server, '/api/sessions/probe', {
      run_id: result.session.run_id,
      probe_pid: sharedProbe.state.shared_probe_pid,
      probe_log_path: sharedProbe.state.shared_probe_log_path,
      probe_kind: 'shared',
    })
    await postSessionEvent(server, result.session.run_id, 'trace_probe_shared_attached', {
      probe_pid: sharedProbe.state.shared_probe_pid,
      probe_log_path: sharedProbe.state.shared_probe_log_path,
      target_root: targetRoot,
    })
  } else if (worker) {
    await postJson(server, '/api/sessions/probe', {
      run_id: result.session.run_id,
      probe_pid: worker.pid,
      probe_log_path: worker.logPath,
      probe_kind: 'run',
    })
  } else {
    let reason = workerFailure ?? sharedProbe.reason ?? probe.reason
    printProbeUnavailableWarning(reason)
    await postSessionEvent(server, result.session.run_id, 'trace_probe_unavailable', {
      platform: probe.platform,
      reason,
      target_root: targetRoot,
    })
  }

  printSession('Started SkillTrace session', server, {
    ...result.session,
    probe_pid: sharedProbe.available
      ? sharedProbe.state?.shared_probe_pid
      : worker?.pid,
    probe_log_path: sharedProbe.available
      ? sharedProbe.state?.shared_probe_log_path
      : worker?.logPath,
    probe_kind: sharedProbe.available ? 'shared' : worker ? 'run' : undefined,
  })
}

async function end(args: string[]) {
  let options = parseArgs(args)
  let server = options.server || process.env.SKILLTRACE_SERVER || DEFAULT_SERVER

  if (options.discard) {
    let active = await getJson(server, '/api/sessions/status')
    if (!active.session) {
      console.log('No active SkillTrace session to discard.')
      return
    }

    if (!options.yes && !(await confirmDiscard(active.session))) {
      console.log('Discard cancelled.')
      return
    }
  }

  await cleanupActiveInjection(server)

  let result = await postJson(server, '/api/sessions/end', {
    discard: options.discard === true,
  })

  if (result.session) {
    if (options.discard) {
      printDiscardedSession(result.session)
    } else {
      printSession('Ended SkillTrace session', server, result.session)
    }
  } else {
    console.log(options.discard
      ? 'No active SkillTrace session to discard.'
      : 'No active SkillTrace session.')
  }
}

async function status(args: string[]) {
  let options = parseArgs(args)
  let server = options.server || process.env.SKILLTRACE_SERVER || DEFAULT_SERVER
  let result = await getJson(server, '/api/sessions/status')

  if (result.session) {
    printSession('Active SkillTrace session', server, result.session)
  } else {
    console.log('No active SkillTrace session.')
  }
}

async function daemon(args: string[]) {
  let [command, ...rest] = args

  if (command === 'start') {
    await daemonStart(rest)
  } else if (command === 'stop') {
    await daemonStop(rest)
  } else if (command === 'status') {
    await daemonStatus(rest)
  } else if (command === 'logs') {
    daemonLogs(rest)
  } else {
    usage(command ? `Unknown daemon command: ${command}` : 'Missing daemon command')
  }
}

async function daemonStart(args: string[]) {
  let options = parseArgs(args)
  let server = options.server || process.env.SKILLTRACE_SERVER || DEFAULT_SERVER
  let bindHost = process.env.HOST || '127.0.0.1'
  let port = process.env.PORT || new URL(server).port || '7555'
  let status = await getDaemonStatus(server)
  let requestSharedProbe = sharedProbeRequested(options)

  if (status.alive) {
    if (status.state) {
      console.log('SkillTrace daemon is already running.')
      printBindChangeHint(status.state, bindHost, port)
      printSharedProbeChangeHint(status.state, requestSharedProbe)
    } else {
      console.log('A SkillTrace server is already responding.')
    }
    printDaemonStatus(status)
    return
  }

  let sharedProbe = await prepareSharedProbe(requestSharedProbe, server)
  fs.mkdirSync(path.dirname(DAEMON_LOG_PATH), { recursive: true })
  let logFd = fs.openSync(DAEMON_LOG_PATH, 'a')
  let child = spawn(serveCommand(), serveArgs(), {
    cwd: PROJECT_ROOT,
    detached: true,
    stdio: ['ignore', logFd, logFd],
    env: {
      ...process.env,
      SKILLTRACE_DAEMON: '1',
    },
  })

  child.unref()
  fs.closeSync(logFd)

  if (typeof child.pid !== 'number') {
    throw new Error('Failed to start SkillTrace daemon')
  }

  if (sharedProbe.requested && process.platform === 'darwin' && !sharedProbe.warning) {
    let candidate = startSharedProbeWorker({
      server,
      debug: options.debugProbe,
    })
    if (await waitForProbeStartup(candidate.pid)) {
      sharedProbe.worker = candidate
    } else {
      sharedProbe.warning = `shared probe exited during startup; check ${candidate.logPath}`
      sharedProbe.blocksRunProbe = true
      killProcessGroup(candidate.pid, 'SIGTERM')
      killProcessTree(candidate.pid, 'SIGTERM')
      await waitForExit(candidate.pid)
    }
  }

  let state = {
    pid: child.pid,
    server,
    bind_host: bindHost,
    bind_port: port,
    ui_urls: displayUrls(bindHost, port),
    log_path: DAEMON_LOG_PATH,
    started_at: new Date().toISOString(),
    shared_probe_requested: sharedProbe.requested,
    shared_probe_pid: sharedProbe.worker?.pid,
    shared_probe_log_path: sharedProbe.worker?.logPath,
    shared_probe_platform: sharedProbe.worker ? process.platform : undefined,
    shared_probe_warning: sharedProbe.warning,
    shared_probe_blocks_run_probe: sharedProbe.blocksRunProbe,
  }

  writeDaemonState(state)

  console.log('Started experimental SkillTrace daemon.')
  console.log(`  pid: ${state.pid}`)
  console.log(`  server: ${state.server}`)
  console.log(`  bind: ${state.bind_host}:${port}`)
  printDisplayUrls(state.ui_urls)
  printSharedProbeDaemonState(state)
  console.log(`  log: ${state.log_path}`)

  let startup = await waitForDaemon(child.pid, server)
  if (startup.ready) {
    console.log('  health: ok')
  } else {
    await stopStartedDaemon(state)
    console.log('  health: not ready yet')
    if (startup.health?.ok) {
      console.log(`  warning: ${server} is responding from pid ${startup.health.pid ?? 'unknown'}, not ${child.pid}`)
    }
    console.log('  check: skilltrace daemon logs')
  }
}

async function daemonStop(args: string[]) {
  let options = parseArgs(args)
  let state = readDaemonState()
  let server = options.server || state?.server || process.env.SKILLTRACE_SERVER || DEFAULT_SERVER

  if (!state) {
    await cleanupSharedProbeWorkers(server)
    console.log('No SkillTrace daemon state found.')
    if (await isServerAlive(server)) console.log(`A server is responding at ${server}.`)
    return
  }

  await cleanupActiveInjection(server)
  await endServerSession(server)
  if (state.shared_probe_pid) {
    await stopProcessTree(state.shared_probe_pid)
  }
  await cleanupSharedProbeWorkers(server)
  if (processAlive(state.pid)) {
    killProcessGroup(state.pid, 'SIGTERM')
    killProcessTree(state.pid, 'SIGTERM')
    await waitForExit(state.pid)
  }
  if (processAlive(state.pid)) {
    killProcessGroup(state.pid, 'SIGKILL')
    killProcessTree(state.pid, 'SIGKILL')
    await waitForExit(state.pid)
  }

  removeDaemonState()
  if (await isServerAlive(server)) {
    console.log('SkillTrace daemon state was removed, but a server is still responding.')
  } else {
    console.log('Stopped SkillTrace daemon.')
  }
}

async function stopStartedDaemon(state: DaemonState) {
  if (state.shared_probe_pid) {
    await stopProcessTree(state.shared_probe_pid)
  }

  await cleanupSharedProbeWorkers(state.server)
  await stopProcessTree(state.pid)
  removeDaemonState()
}


function startProbeWorker(options: ProbeWorkerOptions) {
  let logPath = path.join(
    DAEMON_DIR,
    'logs/probes',
    `traceskill-probe-${options.runId}.log`,
  )
  fs.mkdirSync(path.dirname(logPath), { recursive: true })
  let logFd = fs.openSync(logPath, 'a')
  let args = [
    ...nodeScriptArgs('scripts/traceskill-probe-worker.ts'),
    '--run',
    options.runId,
    '--target',
    options.targetRoot,
    '--server',
    options.server,
  ]
  if (options.debug) args.push('--debug')

  let child = spawn(
    process.execPath,
    args,
    {
      detached: false,
      stdio: ['ignore', logFd, logFd],
      env: process.env,
    },
  )

  child.unref()
  fs.closeSync(logFd)

  if (typeof child.pid !== 'number') {
    throw new Error('Failed to start SkillTrace probe worker')
  }

  return {
    pid: child.pid,
    logPath,
  }
}


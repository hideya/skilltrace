async function prepareSharedProbe(
  requested: boolean,
  server: string,
): Promise<PreparedSharedProbe> {
  if (!requested) {
    return {
      requested: false,
    }
  }

  let sharedWorkers = sharedProbeWorkers()
  let foreignWorker = sharedWorkers.find((worker) =>
    worker.server && worker.server !== server
  )
  if (foreignWorker) {
    return {
      requested: true,
      warning: `another shared probe is already running for ${foreignWorker.server ?? 'an unknown server'}`,
      blocksRunProbe: true,
    }
  }

  let staleWorkers = sharedWorkers.filter((worker) =>
    worker.server === server || !worker.server
  )
  if (staleWorkers.length > 0) {
    for (let worker of staleWorkers) {
      await stopProcessTree(worker.pid)
    }
  }

  let existing = readDaemonState()
  if (
    existing?.shared_probe_pid &&
    existing.server !== server &&
    processAlive(existing.shared_probe_pid)
  ) {
    return {
      requested: true,
      warning: `another shared probe is already running for ${existing.server}`,
      blocksRunProbe: true,
    }
  }

  if (process.platform !== 'darwin') {
    return {
      requested: true,
      warning: 'shared probe is macOS-only; this platform uses per-run probing',
    }
  }

  if (!commandExists('fs_usage')) {
    return {
      requested: true,
      warning: 'fs_usage was not found on PATH',
    }
  }

  primeSudo()

  return {
    requested: true,
  }
}

function sharedProbeStatus(server: string): SharedProbeStatus {
  let state = readDaemonState()
  if (!state?.shared_probe_requested) {
    return {
      requested: false,
      available: false,
    }
  }

  if (state.server !== server) {
    return {
      requested: true,
      available: false,
      state,
      reason: `daemon shared probe belongs to ${state.server}`,
    }
  }

  if (state.shared_probe_warning) {
    return {
      requested: true,
      available: false,
      state,
      reason: state.shared_probe_warning,
      blocksRunProbe: state.shared_probe_blocks_run_probe,
    }
  }

  if (state.shared_probe_pid && processAlive(state.shared_probe_pid)) {
    return {
      requested: true,
      available: true,
      state,
    }
  }

  return {
    requested: true,
    available: false,
    state,
    reason: 'shared probe process is not running',
  }
}


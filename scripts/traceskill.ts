async function daemonStart(args: string[]) {
  let options = parseArgs(args)
  let server = options.server || process.env.SKILLTRACE_SERVER || DEFAULT_SERVER
  let bindHost = process.env.HOST || '127.0.0.1'
  let port = process.env.PORT || new URL(server).port || '7555'
  let status = await getDaemonStatus(server)
  let requestSharedProbe = sharedProbeRequested(options)

  if (status.alive) {
    if (status.state) {
      console.log('SkillTrace daemon is already running.')
      printBindChangeHint(status.state, bindHost, port)
      printSharedProbeChangeHint(status.state, requestSharedProbe)
    } else {
      console.log('A SkillTrace server is already responding.')
    }
    printDaemonStatus(status)
    return
  }

  let sharedProbe = await prepareSharedProbe(requestSharedProbe, server)
  fs.mkdirSync(path.dirname(DAEMON_LOG_PATH), { recursive: true })
  let logFd = fs.openSync(DAEMON_LOG_PATH, 'a')
  let child = spawn(serveCommand(), serveArgs(), {
    cwd: PROJECT_ROOT,
    detached: true,
    stdio: ['ignore', logFd, logFd],
    env: {
      ...process.env,
      SKILLTRACE_DAEMON: '1',
    },
  })

  child.unref()
  fs.closeSync(logFd)

  if (typeof child.pid !== 'number') {
    throw new Error('Failed to start SkillTrace daemon')
  }

  if (sharedProbe.requested && process.platform === 'darwin' && !sharedProbe.warning) {
    let candidate = startSharedProbeWorker({
      server,
      debug: options.debugProbe,
    })
    if (await waitForProbeStartup(candidate.pid)) {
      sharedProbe.worker = candidate
    } else {
      sharedProbe.warning = `shared probe exited during startup; check ${candidate.logPath}`
      sharedProbe.blocksRunProbe = true
      killProcessGroup(candidate.pid, 'SIGTERM')
      killProcessTree(candidate.pid, 'SIGTERM')
      await waitForExit(candidate.pid)
    }
  }

  let state = {
    pid: child.pid,
    server,
    bind_host: bindHost,
    bind_port: port,
    ui_urls: displayUrls(bindHost, port),
    log_path: DAEMON_LOG_PATH,
    started_at: new Date().toISOString(),
    shared_probe_requested: sharedProbe.requested,
    shared_probe_pid: sharedProbe.worker?.pid,
    shared_probe_log_path: sharedProbe.worker?.logPath,
    shared_probe_platform: sharedProbe.worker ? process.platform : undefined,
    shared_probe_warning: sharedProbe.warning,
    shared_probe_blocks_run_probe: sharedProbe.blocksRunProbe,
  }

  writeDaemonState(state)

  console.log('Started experimental SkillTrace daemon.')
  console.log(`  pid: ${state.pid}`)
  console.log(`  server: ${state.server}`)
  console.log(`  bind: ${state.bind_host}:${port}`)
  printDisplayUrls(state.ui_urls)
  printSharedProbeDaemonState(state)
  console.log(`  log: ${state.log_path}`)

  let startup = await waitForDaemon(child.pid, server)
  if (startup.ready) {
    console.log('  health: ok')
  } else {
    await stopStartedDaemon(state)
    console.log('  health: not ready yet')
    if (startup.health?.ok) {
      console.log(`  warning: ${server} is responding from pid ${startup.health.pid ?? 'unknown'}, not ${child.pid}`)
    }
    console.log('  check: skilltrace daemon logs')
  }
}

async function daemonStop(args: string[]) {
  let options = parseArgs(args)
  let state = readDaemonState()
  let server = options.server || state?.server || process.env.SKILLTRACE_SERVER || DEFAULT_SERVER

  if (!state) {
    await cleanupSharedProbeWorkers(server)
    console.log('No SkillTrace daemon state found.')
    if (await isServerAlive(server)) console.log(`A server is responding at ${server}.`)
    return
  }

  await cleanupActiveInjection(server)
  await endServerSession(server)
  if (state.shared_probe_pid) {
    await stopProcessTree(state.shared_probe_pid)
  }
  await cleanupSharedProbeWorkers(server)
  if (processAlive(state.pid)) {
    killProcessGroup(state.pid, 'SIGTERM')
    killProcessTree(state.pid, 'SIGTERM')
    await waitForExit(state.pid)
  }
  if (processAlive(state.pid)) {
    killProcessGroup(state.pid, 'SIGKILL')
    killProcessTree(state.pid, 'SIGKILL')
    await waitForExit(state.pid)
  }

  removeDaemonState()
  if (await isServerAlive(server)) {
    console.log('SkillTrace daemon state was removed, but a server is still responding.')
  } else {
    console.log('Stopped SkillTrace daemon.')
  }
}

async function stopStartedDaemon(state: DaemonState) {
  if (state.shared_probe_pid) {
    await stopProcessTree(state.shared_probe_pid)
  }

  await cleanupSharedProbeWorkers(state.server)
  await stopProcessTree(state.pid)
  removeDaemonState()
}


function passiveProbeSupport() {
  if (process.platform === 'darwin') {
    return {
      supported: true,
      platform: process.platform,
    }
  }

  if (process.platform === 'linux') {
    if (commandExists('inotifywait')) {
      return {
        supported: true,
        platform: process.platform,
      }
    }

    return {
      supported: false,
      platform: process.platform,
      reason: 'Passive file probing on linux requires inotifywait. Install inotify-tools to enable passive tracing.',
    }
  }

  return {
    supported: false,
    platform: process.platform,
    reason: `Passive file probing is not available on ${process.platform} yet; semantic tracing will still run.`,
  }
}

